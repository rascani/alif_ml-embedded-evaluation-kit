"""Size a registry whose ordinary and primitive operators are both selected.

The upstream capacity generator reserves space for every primitive operator.
Here the selected YAML already includes the required primitives, so adding that
allowance would count them twice.
"""

import argparse
from pathlib import Path

import yaml


def generate_registry_header(oplist: Path, output: Path) -> int:
    """Count selected kernel variants and emit the runtime's capacity header.

    :param oplist:       Model-derived selected_operators.yaml.
    :param output:       Header consumed by operator_registry.cpp.
    :returns:            Registry capacity, with one slot for an empty graph.
    :raises ValueError:  Selection requests unspecified operators or overloads.
    """
    selection = yaml.safe_load(oplist.read_text(encoding="utf-8")) or {}
    operators = selection.get("operators") or {}
    metadata = selection.get("et_kernel_metadata") or {}
    if selection.get("include_all_operators") or any(
        properties.get("include_all_overloads") for properties in operators.values()
    ):
        raise ValueError("Primitive selection requires explicit operators and overloads")

    count = 0
    for name in operators.keys() | metadata.keys():
        variants = metadata.get(name) or ["default"]
        count += len(set(variants))
    count = max(1, count)
    header = (
        "// Generated by mlek_tools.gen.gen_et_registry. Do not edit.\n"
        "#pragma once\n"
        f"#define EXECUTORCH_SELECTED_MAX_KERNEL_NUM {count}\n"
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.exists() or output.read_text(encoding="utf-8") != header:
        output.write_text(header, encoding="utf-8")
    return count


def main():
    """Generate a capacity header from the command-line arguments."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--oplist-yaml", type=Path, required=True)
    parser.add_argument("--output-path", type=Path, required=True)
    args = parser.parse_args()
    count = generate_registry_header(args.oplist_yaml, args.output_path)
    print(f"Selected ExecuTorch registry capacity: {count}")


if __name__ == "__main__":
    main()
